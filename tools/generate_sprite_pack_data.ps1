    $plainTokens.Count, $megaTokens.Count, $femaleTokens.Count, $numericTokens.Count)

# Resolution accumulators
$resolved = New-Object System.Collections.Generic.List[object]   # {token,id,category,note}
$skipped  = New-Object System.Collections.Generic.List[object]   # {token,category,reason}

# ---------------------------------------------------------------------------
# PLAIN resolution
# ---------------------------------------------------------------------------
# Build a verified, collision-free "underscore-stripped id -> real id" map
# across the FULL known-id universe (native vanilla + all national.lua ids)
# once, up front -- this lets folder tokens that dropped an underscore
# (HOOH -> HO_OH, TAPUKOKO -> TAPU_KOKO, MRMIME -> MR_MIME, ...) resolve via
# a mechanical, auditable normalization instead of a guess. Collisions (two
# distinct real ids collapsing to the same stripped string) would abort the
# whole pass rather than silently pick one.
$knownIdUniverse = ($native + $allNationalIds) | Select-Object -Unique
$strippedMap = @{}
$stripCollisions = New-Object System.Collections.Generic.List[string]
foreach ($id in $knownIdUniverse) {
    $stripped = $id -replace '_', ''
    if ($strippedMap.ContainsKey($stripped)) {
        $stripCollisions.Add("$stripped <- $id AND $($strippedMap[$stripped])")
    } else {
        $strippedMap[$stripped] = $id
    }
}
if ($stripCollisions.Count -gt 0) {
    Write-Warning "Underscore-stripped id collisions detected -- normalization pass DISABLED for safety:"
    $stripCollisions | ForEach-Object { Write-Warning "  $_" }
    $strippedMap = @{}
}

# Two known, unambiguous non-underscore abbreviations that the stripping
# pass alone can't catch (folder used FE/MA rather than F/M).
$plainManualOverrides = @{
    "NIDORANFE" = "NIDORAN_F"
    "NIDORANMA" = "NIDORAN_M"
}

foreach ($t in $plainTokens) {
    if ($native -contains $t) {
        $resolved.Add([PSCustomObject]@{ token=$t; id=$t; category="plain"; note="exact match, native vanilla" })
    } elseif ($allNationalIds -contains $t) {
        $resolved.Add([PSCustomObject]@{ token=$t; id=$t; category="plain"; note="exact match, national_dex" })
    } elseif ($plainManualOverrides.ContainsKey($t)) {
        $mapped = $plainManualOverrides[$t]
        $resolved.Add([PSCustomObject]@{ token=$t; id=$mapped; category="plain"; note="known abbreviation (FE/MA -> F/M)" })
    } elseif ($strippedMap.ContainsKey($t)) {
        $mapped = $strippedMap[$t]
        $resolved.Add([PSCustomObject]@{ token=$t; id=$mapped; category="plain"; note="underscore-stripped match (verified collision-free)" })
    } else {
        $skipped.Add([PSCustomObject]@{ token=$t; category="plain"; reason="no matching registered species (not in native vanilla 251 or national_dex, even after underscore-stripped normalization)" })
    }
}

# ---------------------------------------------------------------------------
# MEGA-FAMILY resolution
# ---------------------------------------------------------------------------
foreach ($t in $megaTokens) {
    $idx = $t.IndexOf("_MEGA")
    $base = $t.Substring(0, $idx)
    $formLabel = $t.Substring($idx + 1)  # "MEGA", "MEGA_X", "MEGA_FORMA_..."

    $matches_ = @($formRecords | Where-Object { $_.baseSpecies -eq $base -and $_.form -eq $formLabel })
    if ($matches_.Count -eq 1) {
        $resolved.Add([PSCustomObject]@{ token=$t; id=$matches_[0].id; category="mega"; note="baseSpecies=$base form=$formLabel" })
    } elseif ($matches_.Count -gt 1) {
        $skipped.Add([PSCustomObject]@{ token=$t; category="mega-family"; reason="multiple matching records for baseSpecies=$base form=$formLabel (ambiguous)" })
    } else {
        # Special-cased explanation for the one real ambiguity found during
        # verification: Meowstic's only Mega records are gender-split
        # (MALE_MEGA / FEMALE_MEGA); the folder token doesn't specify which.
        if ($base -eq "MEOWSTIC" -and $formLabel -eq "MEGA") {
            $skipped.Add([PSCustomObject]@{ token=$t; category="mega-family"; reason="MEOWSTIC's real Mega forms are gender-split (MALE_MEGA/FEMALE_MEGA in national_dex); the plain MEOWSTIC_MEGA folder token does not specify which, so it cannot be resolved without guessing" })
        } else {
            $skipped.Add([PSCustomObject]@{ token=$t; category="mega-family"; reason="no canonical Mega/alt-form exists for this species in national_dex (baseSpecies=$base form=$formLabel not found)" })
        }
    }
}

# ---------------------------------------------------------------------------
# NUMERIC-SUFFIX resolution
# ---------------------------------------------------------------------------
# Vivillon/Alcremie are excluded outright per explicit user instruction --
# base-only, all numbered pattern/flavor variants dropped.
$excludedNumeric = @($numericTokens | Where-Object { $_ -match '^(VIVILLON|ALCREMIE)_\d+$' })
foreach ($t in $excludedNumeric) {
    $skipped.Add([PSCustomObject]@{ token=$t; category="numeric"; reason="excluded by instruction (cosmetic pattern/flavor variant, base-only)" })
}
$numericToResolve = @($numericTokens | Where-Object { $_ -notmatch '^(VIVILLON|ALCREMIE)_\d+$' })

# Group remaining numeric tokens by base species.
$numGroups = @{}
foreach ($t in $numericToResolve) {
    if ($t -match '^(.+)_(\d+)$') {
        $base = $matches[1]
        if (-not $numGroups.ContainsKey($base)) { $numGroups[$base] = New-Object System.Collections.Generic.List[string] }
        $numGroups[$base].Add($t)
    }
}

# Tier 2: a short, individually-verified hand list for well-known
# multi-form species where the real in-game (or Pokedex-fixed) form order
# is unambiguous -- NOT alphabetical guessing. Each id below is re-verified
# against national.lua's actual form records below before being trusted;
# if verification fails for any entry, that specific token falls through
# to Tier 3 rather than being forced.
#   DEOXYS/ROTOM: literal in-game "change form" menu order.
#   CASTFORM: canonical weather-form order (Bulbapedia/every game datamine).
#   ORICORIO/WORMADAM/CRAMORANT/LYCANROC/SQUAWKABILLY/TAUROS/TERAPAGOS:
#     fixed Pokedex/story form-listing order used consistently in-game.
#   BASCULIN: folder numbering starts at _2 (not _1), consistent with "_1"
#     being reserved for the base Red-Striped (the plain BASCULIN folder);
#     Blue-Striped predates White-Striped by 3 generations, matching _2/_3.
#   DARMANITAN: Bulbapedia's fixed infobox form order (Standard/Zen/
#     Galar-Standard/Galar-Zen), Standard being the plain DARMANITAN folder.
$tier2Map = @{
    "DEOXYS"        = @{ "1"="ATTACK"; "2"="DEFENSE"; "3"="SPEED" }
    "ROTOM"         = @{ "1"="HEAT"; "2"="WASH"; "3"="FROST"; "4"="FAN"; "5"="MOW" }
    "CASTFORM"      = @{ "1"="SUNNY"; "2"="RAINY"; "3"="SNOWY" }
    "ORICORIO"      = @{ "1"="POM_POM"; "2"="PAU"; "3"="SENSU" }
    "WORMADAM"      = @{ "1"="SANDY"; "2"="TRASH" }
    "CRAMORANT"     = @{ "1"="GULPING"; "2"="GORGING" }
    "TERAPAGOS"     = @{ "1"="TERASTAL"; "2"="STELLAR" }
    "TAUROS"        = @{ "1"="PALDEA_COMBAT_BREED"; "2"="PALDEA_BLAZE_BREED"; "3"="PALDEA_AQUA_BREED" }
    "SQUAWKABILLY"  = @{ "1"="BLUE_PLUMAGE"; "2"="YELLOW_PLUMAGE"; "3"="WHITE_PLUMAGE" }
    "LYCANROC"      = @{ "1"="MIDNIGHT"; "2"="DUSK" }
    "BASCULIN"      = @{ "2"="BLUE_STRIPED"; "3"="WHITE_STRIPED" }
    "DARMANITAN"    = @{ "1"="ZEN"; "2"="GALAR_STANDARD"; "3"="GALAR_ZEN" }
}

foreach ($base in ($numGroups.Keys | Sort-Object)) {
    $tokens = $numGroups[$base]
    $nonMegaForms = @($formRecords | Where-Object { $_.baseSpecies -eq $base -and $_.form -notmatch 'MEGA|GMAX|GIGANTAMAX' })

    if ($tokens.Count -eq 1 -and $nonMegaForms.Count -eq 1) {
        # Tier 1: exactly one non-Mega/Gmax alt form AND exactly one numeric
        # folder for this species -- a safe 1:1 identity match, not a guess.
        $resolved.Add([PSCustomObject]@{ token=$tokens[0]; id=$nonMegaForms[0].id; category="numeric-tier1"; note="baseSpecies=$base form=$($nonMegaForms[0].form), single unambiguous alt form" })
        continue
    }

    if ($tier2Map.ContainsKey($base)) {
        $formMap = $tier2Map[$base]
        $allOk = $true
        $pending = New-Object System.Collections.Generic.List[object]
        foreach ($tok in $tokens) {
            if ($tok -match '_(\d+)$') {
                $numSuffix = $matches[1]
                if ($formMap.ContainsKey($numSuffix)) {
                    $expectedForm = $formMap[$numSuffix]
                    $match = @($nonMegaForms | Where-Object { $_.form -eq $expectedForm })
                    if ($match.Count -eq 1) {
                        $pending.Add([PSCustomObject]@{ token=$tok; id=$match[0].id; category="numeric-tier2"; note="hand-mapped + verified: baseSpecies=$base form=$expectedForm" })
                    } else {
                        $allOk = $false
                    }
                } else {
                    $allOk = $false
                }
            }
        }
        if ($allOk -and $pending.Count -eq $tokens.Count) {
            foreach ($p in $pending) { $resolved.Add($p) }
            continue
        }
        # fall through to Tier 3 if verification failed for any token in the group
    }

    # Tier 3: insufficient evidence -- explain WHY (mismatch shape) rather
    # than a generic message, so the report is auditable.
    $formCount = $nonMegaForms.Count
    $formList = if ($formCount -gt 0) { ($nonMegaForms | ForEach-Object { $_.form }) -join "," } else { "(none)" }
    $reason = "insufficient evidence to confidently map numeric variant(s) to a real form -- $($tokens.Count) numeric folder(s) [$($tokens -join ',')] vs $formCount registered non-Mega/Gmax alt form(s) [$formList] for baseSpecies=$base; no safe 1:1 identity match and no verified Tier 2 domain mapping covers this case"
    foreach ($tok in $tokens) {
        $skipped.Add([PSCustomObject]@{ token=$tok; category="numeric"; reason=$reason })
    }
}

# ---------------------------------------------------------------------------
# FEMALE ("_F") resolution -- cosmetic bucket, except the 4 real _FEMALE ids
# ---------------------------------------------------------------------------
$realFemaleSpecies = @{
    "MEOWSTIC"    = "MEOWSTIC_FEMALE"
    "INDEEDEE"    = "INDEEDEE_FEMALE"
    "BASCULEGION" = "BASCULEGION_FEMALE"
    "OINKOLOGNE"  = "OINKOLOGNE_FEMALE"
}
# Universe of ids resolved so far (plain + mega + numeric tiers), so a
# compound token like SNEASEL_1_F can resolve against SNEASEL_1's resolved
# real id (SNEASEL_HISUI) rather than being treated as unresolvable.
$resolvedByToken = @{}
foreach ($r in $resolved) { $resolvedByToken[$r.token] = $r.id }

$cosmeticFemale = New-Object System.Collections.Generic.List[object]  # {baseToken, resolvedId, folderToken}

foreach ($t in $femaleTokens) {
    $baseToken = $t.Substring(0, $t.Length - 2)  # strip trailing "_F"

    if ($realFemaleSpecies.ContainsKey($baseToken)) {
        # Would resolve directly as a distinct roster id if this exact
        # folder shape ever appears (none currently do -- the 4 known
        # species use numeric-suffix folders instead, handled above).
        $resolved.Add([PSCustomObject]@{ token=$t; id=$realFemaleSpecies[$baseToken]; category="female-real"; note="real distinct _FEMALE id, not cosmetic" })
        continue
    }

    if ($resolvedByToken.ContainsKey($baseToken)) {
        $realId = $resolvedByToken[$baseToken]
        $cosmeticFemale.Add([PSCustomObject]@{ baseToken=$baseToken; resolvedId=$realId; folderToken=$t })
    } elseif ($native -contains $baseToken -or $allNationalIds -contains $baseToken) {
        # base token itself is a real id even though it wasn't independently
        # walked through the plain-token loop (defensive fallback).
        $cosmeticFemale.Add([PSCustomObject]@{ baseToken=$baseToken; resolvedId=$baseToken; folderToken=$t })
    } else {
        $skipped.Add([PSCustomObject]@{ token=$t; category="female"; reason="base token '$baseToken' does not resolve to a real registered species (skipped or unresolved itself), so no species exists to attach this cosmetic female art to" })
    }
}

Write-Host ("Resolved: {0}  Skipped: {1}  Cosmetic-female folders: {2}" -f $resolved.Count, $skipped.Count, $cosmeticFemale.Count)

