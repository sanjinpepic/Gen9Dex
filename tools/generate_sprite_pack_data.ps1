$plainTokens  = New-Object System.Collections.Generic.List[string]
$megaTokens   = New-Object System.Collections.Generic.List[string]
$femaleTokens = New-Object System.Collections.Generic.List[string]
$numericTokens= New-Object System.Collections.Generic.List[string]
foreach ($t in $allTokens) {
    switch (Get-TokenCategory $t) {
        "mega"    { $megaTokens.Add($t) }
        "female"  { $femaleTokens.Add($t) }
