<#
  generate_sprite_pack_data.ps1

  BUILD-TIME-ONLY TOOL -- not shipped mod logic, not loaded by the game.
  Run this offline, directly against the checked-out repos on disk, whenever
  new folders are added under GalarGmaxDex/assets/front|back/ and the
  full-roster sprite pack data needs regenerating.

  What it does (Phase 1 of the full-roster battle sprite pack plan):
    1. Builds the authoritative "native vanilla" species id list (Kanto 151
       from gen1recomp-dev's own ROM-extracted data/generated/pokemon.lua,
       plus the 100 Johto-only ids from tools/rom_manifest_gold.json's
       pokemonAssets key set, cross-validated against national_dex's own
       register table so the exact spelling convention is confirmed).
    2. Parses national_dex's data/species/generated/national.lua into a flat
       record list (id, dex, form, baseSpecies, section) so folder tokens
       can be cross-referenced against real registered content instead of
       guessed.
    3. Enumerates every GalarGmaxDex/assets/front/<TOKEN> folder, categorizes
       each token (plain / mega-family / female "_F" / numeric-suffix), and
       resolves each to a real content id using ONLY verifiable evidence:
         - plain: exact id match (with a verified, collision-free
           underscore-stripping normalization pass for tokens whose folder
           name dropped an underscore national_dex/the engine keeps, e.g.
           HOOH -> HO_OH, TAPUKOKO -> TAPU_KOKO -- confirmed zero collisions
           across the full ~1600-id universe before this pass is trusted).
         - mega-family: baseSpecies+form cross-reference against
           national.lua's register table.
         - numeric-suffix: tiered (Tier 1 mechanical single-form identity
           match; Tier 2 a short, individually-verified hand list for
           well-known multi-form species; Tier 3 skip+log everything left).
         - "_F": cosmetic-female bucket (base species -> folder), except the
           4 species with a REAL separate "_FEMALE" id in national_dex.
    4. Measures front/back frame counts and first-frame native pixel size
       for every resolved id and every genuine "_F" cosmetic folder, via
       System.Drawing.Image (no resampling, just reading existing PNGs).
    5. Emits species/sprite_pack_roster_full.lua,
       overworld/sprite_frames_full.lua, overworld/sprite_gender_cosmetic.lua,
       and a full resolution report (paths below).

  Nothing here touches main.lua, custom_sprite_species.lua or
  sprite_frames.lua -- Phase 1 only produces new, additive data files.
#>

