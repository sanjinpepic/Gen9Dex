# ===========================================================================
# STEP 1 -- authoritative native vanilla species id list (251: Kanto+Johto)
# ===========================================================================
function Get-NativeVanillaList {
    # Kanto 151: gen1recomp-dev\data\generated\pokemon.lua is generated by
    # tools/build_data.py directly from the canonical Red ROM's BaseStats /
    # MonsterNames tables -- this is the real in-engine spelling convention
    # (e.g. FARFETCHD, MR_MIME, NIDORAN_F -- single underscore, no filler).
    $pokemonLuaPath = Join-Path $EngineRoot "data\generated\pokemon.lua"
    $kantoIds = Select-String -Path $pokemonLuaPath -Pattern '^  ([A-Z0-9_]+) = \{' |
        ForEach-Object { $_.Matches[0].Groups[1].Value }

    # Johto 152-251: tools/rom_manifest_gold.json's pokemonAssets keys (a
    # generation:2 manifest, confirmed by src/core/GameVersion.lua as the
    # Gold/Johto import manifest). Its own spelling convention differs
    # slightly from pokemon.lua's for 2 Kanto species it also lists
    # (FARFETCH_D, MR__MIME vs the real FARFETCHD, MR_MIME) -- those 2 are
    # dropped here since the Kanto set above already has the correct
    # spelling; every other Johto-only name was cross-validated against
    # national_dex's national.lua register table (which registers Johto
    # 152-251 as plain species for Red-context play) and matched exactly.
    $manifestPath = Join-Path $EngineRoot "tools\rom_manifest_gold.json"
    $manifest = Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json
    $goldNames = $manifest.pokemonAssets.PSObject.Properties.Name
    $johtoOnly = $goldNames | Where-Object {
        ($kantoIds -notcontains $_) -and $_ -ne "FARFETCH_D" -and $_ -ne "MR__MIME"
    }

    return ($kantoIds + $johtoOnly) | Select-Object -Unique
}

# ===========================================================================
# STEP 1b -- parse national_dex's national.lua into flat records
# ===========================================================================
function Get-NationalRecords {
    $path = Join-Path $NationalDexRoot "data\species\generated\national.lua"
    $lines = Get-Content -LiteralPath $path -Encoding UTF8

    $records = New-Object System.Collections.Generic.List[object]
    $section = $null
    $curKey = $null; $curId = $null; $curDex = $null; $curForm = $null; $curBaseSpecies = $null
    $inRecord = $false

    function Flush {
        if ($inRecord -and $curKey) {
            $records.Add([PSCustomObject]@{
                section = $section; key = $curKey; id = $curId; dex = $curDex
                form = $curForm; baseSpecies = $curBaseSpecies
            })
        }
    }

    foreach ($line in $lines) {
        if ($line -match '^\s*patch = \{\s*$')    { $section = "patch"; continue }
        if ($line -match '^\s*register = \{\s*$') { $section = "register"; continue }
        if ($line -match '^\s*text = \{\s*$')     { $section = "text"; continue }

        if ($line -match '^    ([A-Za-z0-9_]+) = \{\s*$') {
            Flush
            $curKey = $matches[1]; $curId = $null; $curDex = $null; $curForm = $null; $curBaseSpecies = $null
            $inRecord = $true
            continue
        }
        if ($inRecord -and $line -match '^    \},\s*$') {
            Flush
            $inRecord = $false; $curKey = $null
            continue
        }
        if ($inRecord) {
            if ($line -match '^\s*id = "([^"]+)",?\s*$')          { $curId = $matches[1]; continue }
            if ($line -match '^\s*dex = (-?\d+),?\s*$')            { $curDex = [int]$matches[1]; continue }
            if ($line -match '^\s*form = "([^"]+)",?\s*$')         { $curForm = $matches[1]; continue }
            if ($line -match '^\s*baseSpecies = "([^"]+)",?\s*$')  { $curBaseSpecies = $matches[1]; continue }
        }
    }
    Flush

    return $records
}

# ===========================================================================
# STEP 2 -- enumerate + categorize folder tokens
# ===========================================================================
function Get-FolderTokens {
    $tokens = Get-ChildItem -LiteralPath $FrontDir -Directory | Select-Object -ExpandProperty Name
    return $tokens | Where-Object { $_ -ne "000" }
}

function Get-TokenCategory([string]$t) {
    if ($t -match '_MEGA')   { return "mega" }
    if ($t -match '_F$')     { return "female" }
    if ($t -match '_(\d+)$') { return "numeric" }
    return "plain"
}

