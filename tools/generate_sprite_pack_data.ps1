# STEP 4 -- measure frame data
# ===========================================================================
function Measure-Side([string]$token, [string]$sideDir) {
    $dir = Join-Path $sideDir $token
    if (-not (Test-Path -LiteralPath $dir)) { return $null }
    $frames = Get-ChildItem -LiteralPath $dir -Filter "*.png" | Sort-Object Name
    if ($frames.Count -eq 0) { return $null }
    $first = $frames[0].FullName
    $img = [System.Drawing.Image]::FromFile($first)
    $w = $img.Width; $h = $img.Height
    $img.Dispose()
    $size = [Math]::Max($w, $h)
    return [PSCustomObject]@{ count = $frames.Count; size = $size; w = $w; h = $h }
}

function Measure-Token([string]$token) {
    $front = Measure-Side $token $FrontDir
    $back  = Measure-Side $token $BackDir
    return [PSCustomObject]@{
        front = if ($front) { $front.count } else { 0 }
        frontSize = if ($front) { $front.size } else { 0 }
        back = if ($back) { $back.count } else { 0 }
        backSize = if ($back) { $back.size } else { 0 }
    }
}

Write-Host "Measuring frame data for resolved roster..."
$measurements = @{}  # token -> measurement (measure by FOLDER TOKEN, not resolved id)
$rosterEntries = New-Object System.Collections.Generic.List[object]  # {id, token, m}
$seenIds = @{}
foreach ($r in $resolved) {
    if ($r.category -eq "female-real") { continue }  # handled with numeric/plain ids normally; but no folder token "_F" exists for these on disk today
    if ($seenIds.ContainsKey($r.id)) {
        Write-Warning "Duplicate resolved id '$($r.id)' from tokens '$($seenIds[$r.id])' and '$($r.token)' -- keeping first"
        continue
    }
    $m = Measure-Token $r.token
    $measurements[$r.token] = $m
    $rosterEntries.Add([PSCustomObject]@{ id=$r.id; token=$r.token; m=$m })
    $seenIds[$r.id] = $r.token
}
Write-Host ("Measured {0} roster entries." -f $rosterEntries.Count)

Write-Host "Measuring frame data for cosmetic female folders..."
$cosmeticEntries = New-Object System.Collections.Generic.List[object]  # {baseId, folderToken, m}
$seenCosmeticBase = @{}
foreach ($c in $cosmeticFemale) {
    if ($seenCosmeticBase.ContainsKey($c.resolvedId)) {
        Write-Warning "Duplicate cosmetic-female base id '$($c.resolvedId)' from folders '$($seenCosmeticBase[$c.resolvedId])' and '$($c.folderToken)' -- keeping first"
        continue
    }
    $m = Measure-Token $c.folderToken
    $cosmeticEntries.Add([PSCustomObject]@{ baseId=$c.resolvedId; folderToken=$c.folderToken; m=$m })
    $seenCosmeticBase[$c.resolvedId] = $c.folderToken
}
Write-Host ("Measured {0} cosmetic-female entries." -f $cosmeticEntries.Count)

